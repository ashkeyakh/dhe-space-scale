// Browser integration checks; requires Playwright on NODE_PATH and installed Edge.
const { chromium }=require('playwright');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-unsafe-swiftshader']});
  try{
    const page=await browser.newPage({viewport:{width:1500,height:1050},deviceScaleFactor:1});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve('output/extrusion_2001_2002.html')).href);
    await page.evaluate(()=>window.dheReady);
    const idle=()=>page.evaluate(()=>window.dheViewer.idle());
    const state=()=>page.evaluate(()=>({edge:dheViewer.state.edge,active:dheViewer.state.active,edgeVisible:dheViewer.state.edgeVisible,faceVisible:dheViewer.state.faceVisible,highlights:[...dheViewer.state.highlights]}));
    assert.ok(await page.locator('#plot canvas').count()>0);
    assert.equal(await page.evaluate(()=>document.getElementById('plot').data.some(t=>t.type==='mesh3d')),false,'initial faces unfilled');
    assert.equal(await page.evaluate(()=>document.getElementById('plot').data.find(t=>t.name==='Dual vertices').x.length),2,'all dual nodes visible');
    assert.equal(await page.evaluate(()=>document.getElementById('plot').data.find(t=>t.name==='Connected dual half-edges').x.length),0);
    await page.screenshot({path:'output/interactive-wireframe.png',fullPage:false});
    for(const key of ['f','s','a','d','v','o','e']){
      const expected=await page.evaluate(key=>DHEGeometry.navigate(dheViewer.model.half_edges,dheViewer.state.edge,key),key);
      await page.locator('#plot').focus();await page.keyboard.press(key);await idle();
      assert.equal((await state()).edge,expected,`${key} navigates`);
    }
    await page.locator('#object').selectOption('1');await idle();
    await page.locator('[data-action=c]').click();await idle();
    assert.equal((await state()).highlights.length,1);
    assert.equal(await page.evaluate(()=>document.getElementById('plot').data.find(t=>t.name==='Current face').opacity),0.13);
    await page.locator('[data-action=x]').click();await idle();assert.equal((await state()).highlights.length,0);
    const beforeClear=(await state()).edge;
    await page.locator('[data-action=k]').click();await idle();assert.equal((await state()).edge,beforeClear);assert.equal((await state()).edgeVisible,false);
    assert.equal((await state()).faceVisible,true);
    await page.locator('[data-action=l]').click();await idle();assert.equal((await state()).faceVisible,false);
    await page.locator('[data-action=f]').click();await idle();assert.equal((await state()).edgeVisible,true);
    await page.locator('[data-action=z]').click();await idle();assert.match(await page.locator('#coordinates').textContent(),/V = \(/);
    await page.locator('#labels').check();await idle();assert.ok(await page.evaluate(()=>document.getElementById('plot').data.some(t=>t.name==='Primal vertex labels')));
    await page.locator('#labels').uncheck();await idle();
    await page.locator('#connectDual').click();await idle();
    assert.equal(await page.evaluate(()=>document.getElementById('plot').data.find(t=>t.name==='Connected dual half-edges').line.color),'#16854d');
    assert.equal(await page.locator('#connectDual').getAttribute('aria-pressed'),'true');
    await page.locator('#sliceEnabled').check();await idle();
    const initial=await page.evaluate(()=>({area:dheViewer.section.area,expected:dheViewer.model.dual_vertices.slice(1).reduce((s,c)=>s+c.area_m2,0),position:dheViewer.state.position}));
    assert.ok(Math.abs(initial.area-initial.expected)<1e-5);
    await page.locator('#plot').focus();await page.keyboard.press('ArrowUp');await idle();
    assert.ok(Math.abs(await page.evaluate(()=>dheViewer.state.position)-initial.position-0.5)<1e-8);
    await page.keyboard.press('ArrowDown');await idle();
    await page.locator('#slicePosition').hover();await page.mouse.wheel(0,-120);await idle();
    await page.waitForFunction(p=>Math.abs(dheViewer.state.position-p-0.5)<1e-8,initial.position);
    await page.locator('#planeKind').selectOption('vertical');await idle();
    assert.ok(Math.abs(await page.evaluate(()=>dheViewer.plane.normal[2]))<1e-8);
    await page.locator('#azimuth').fill('35');await page.locator('#azimuth').dispatchEvent('input');await idle();
    await page.locator('#planeKind').selectOption('inclined');await idle();
    await page.locator('#tilt').fill('35');await page.locator('#tilt').dispatchEvent('input');await idle();
    const residual=await page.evaluate(()=>Math.max(0,...dheViewer.section.cells.flatMap(c=>c.segments.flat()).map(p=>Math.abs(DHEGeometry.dot(DHEGeometry.sub(p,dheViewer.plane.origin),dheViewer.plane.normal)))));
    assert.ok(residual<1e-6,'all slice vertices lie in the requested plane');
    await page.locator('#object').selectOption('1');await idle();
    await page.locator('[data-action=c]').click();await idle();
    await page.screenshot({path:'output/interactive-slicing.png',fullPage:false});
    await page.locator('#graphView').selectOption('dual');await idle();
    assert.equal(await page.evaluate(()=>document.getElementById('plot').data[0].x.length),0);
    assert.equal(await page.evaluate(()=>document.getElementById('plot').data.find(t=>t.name==='Dual vertices').x.length),2);
    await page.locator('#sliceEnabled').uncheck();await idle();
    await page.screenshot({path:'output/dual-graph.png',fullPage:false});
    await page.locator('#graphView').selectOption('both');await idle();
    await page.locator('#planeKind').selectOption('horizontal');await idle();
    await page.locator('#height').fill('20');await page.locator('#height').dispatchEvent('input');await idle();
    assert.equal(await page.evaluate(()=>dheViewer.state.position),10);
    await page.locator('#height').fill('10');await page.locator('#height').dispatchEvent('input');await idle();
    await page.locator('#edgeId').focus();const old=(await state()).edge;
    await page.keyboard.press('f');assert.equal((await state()).edge,old);
    await page.locator('#edgeId').fill('0');await page.keyboard.press('Enter');await idle();assert.equal((await state()).edge,0);
    await page.locator('#edgeId').fill('999999');await page.locator('#goEdge').click();await idle();assert.match(await page.locator('#notice').textContent(),/Choose an edge ID/);
    await page.locator('[data-action=l]').click();await idle();
    await page.locator('[data-action=x]').click();await idle();
    await page.locator('#connectDual').click();await idle();
    await page.locator('#resetCamera').click();
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.getElementById('plot')._fullLayout.width<=390);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=390),'mobile no horizontal overflow');
    await page.screenshot({path:'output/mobile-check.png',fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('PASS: wireframe initial state; all keyboard operators and buttons; highlights/clear; labels/coordinates; real dual links; all slice orientations, arrow/wheel movement; height; input focus; mobile; no browser errors.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
